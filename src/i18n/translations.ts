export function translateKey(
  locale: AppLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const template = TRANSLATIONS[locale]?.[key] ?? TRANSLATIONS.pt[key] ?? key;
  if (!vars) {
    return template;
  }
  return template.replace(/\{\{\s*(\w+)\s*\}\}|\{\s*(\w+)\s*\}/g, (match, doubleKey, singleKey) => {
    const varName = (doubleKey ?? singleKey) as string;
    const replacement = vars[varName];
    return replacement !== undefined && replacement !== null ? String(replacement) : match;
  });
}
